    private void tpl(String category, String title, String desc, Object[][] questions) {
        Survey s = new Survey();
        s.setUserId(0);
        s.setTitle(title);
        s.setDescription(desc);
        s.setStatus(0);
        s.setIsTemplate(1);
        s.setTemplateCategory(category);
        s.setDeleted(0);
        s.setViewCount(0);
        surveyMapper.insert(s);

        int order = 0;
        for (Object[] q : questions) {
            String qTitle = (String) q[0];
            int qType = (int) q[1];
            String[] options = (String[]) q[2];

            Question question = new Question();
            question.setSurveyId(s.getId());
            question.setTitle(qTitle);
            question.setType(qType);
            question.setRequired(0);
            question.setSortOrder(order++);
            questionMapper.insert(question);

            if (options != null) {
                int optOrder = 0;
                for (String optContent : options) {
                    Option opt = new Option();
                    opt.setQuestionId(question.getId());
                    opt.setContent(optContent);
                    opt.setSortOrder(optOrder++);
                    optionMapper.insert(opt);
                }
            }
        }
    }
